import * as XLSX from 'xlsx';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export interface ExportMetadata {
  reportTitle: string;
  generatedBy: string;
  filterSummary?: string;
  generatedAt?: string;
}

function buildFilename(baseName: string, ext: string): string {
  const slug = baseName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  const datePart = new Date().toISOString().slice(0, 10);
  return `${slug}-${datePart}.${ext}`;
}

export function exportToCsv(
  rows: Record<string, string | number | null | undefined>[],
  metadata: ExportMetadata
): void {
  const generatedAt = metadata.generatedAt ?? new Date().toLocaleString();
  const headers = rows.length > 0 ? Object.keys(rows[0]) : ['Message'];
  const escapeCsv = (value: unknown) => {
    const str = value === null || value === undefined ? '' : String(value);
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const lines = [
    `# Report,${escapeCsv(metadata.reportTitle)}`,
    `# Generated By,${escapeCsv(metadata.generatedBy)}`,
    `# Generated At,${escapeCsv(generatedAt)}`,
    `# Filters,${escapeCsv(metadata.filterSummary || 'All Assigned Records')}`,
    '',
    headers.map(escapeCsv).join(','),
    ...(rows.length > 0
      ? rows.map((row) => headers.map((h) => escapeCsv(row[h])).join(','))
      : ['No authorized records matched the selected filters']),
  ];

  const blob = new Blob([lines.join('\r\n')], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = buildFilename(metadata.reportTitle, 'csv');
  link.click();
  URL.revokeObjectURL(url);
}

export function exportToExcel(
  rows: Record<string, string | number | null | undefined>[],
  metadata: ExportMetadata
): void {
  const generatedAt = metadata.generatedAt ?? new Date().toLocaleString();
  const workbook = XLSX.utils.book_new();

  const metaSheet = XLSX.utils.aoa_to_sheet([
    ['SmartBridge InternFlow – LAUNCHPAD Report'],
    ['Report Title', metadata.reportTitle],
    ['Generated By', metadata.generatedBy],
    ['Generated At', generatedAt],
    ['Filters Applied', metadata.filterSummary || 'All Assigned Records'],
  ]);
  XLSX.utils.book_append_sheet(workbook, metaSheet, 'Metadata');

  const dataSheet = XLSX.utils.json_to_sheet(
    rows.length > 0 ? rows : [{ Status: 'No authorized records matched the selected filters' }]
  );
  XLSX.utils.book_append_sheet(workbook, dataSheet, 'Report Data');

  XLSX.writeFile(workbook, buildFilename(metadata.reportTitle, 'xlsx'));
}

export function exportToPdf(
  rows: Record<string, string | number | null | undefined>[],
  metadata: ExportMetadata
): void {
  const generatedAt = metadata.generatedAt ?? new Date().toLocaleString();
  const doc = new jsPDF({ orientation: rows.length > 0 && Object.keys(rows[0]).length > 5 ? 'landscape' : 'portrait' });

  doc.setFontSize(14);
  doc.setTextColor(23, 43, 77);
  doc.text(`SmartBridge InternFlow – ${metadata.reportTitle}`, 14, 16);

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(`Generated By: ${metadata.generatedBy}  |  Date: ${generatedAt}`, 14, 23);
  doc.text(`Filters: ${metadata.filterSummary || 'All Assigned Records'}`, 14, 28);

  const headers = rows.length > 0 ? Object.keys(rows[0]) : ['Notice'];
  const body =
    rows.length > 0
      ? rows.map((row) => headers.map((h) => String(row[h] ?? '—')))
      : [['No authorized records matched the selected filters.']];

  autoTable(doc, {
    startY: 34,
    head: [headers],
    body,
    styles: { fontSize: 8, cellPadding: 2.5 },
    headStyles: { fillColor: [23, 43, 77], textColor: 255 },
    alternateRowStyles: { fillColor: [245, 247, 250] },
  });

  doc.save(buildFilename(metadata.reportTitle, 'pdf'));
}

